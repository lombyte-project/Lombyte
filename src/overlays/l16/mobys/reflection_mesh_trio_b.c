/* Moby class 1953 */
void reflection_mesh_trio_b_update(struct Moby *moby) {
    enum {
        MESH_RENDER_INITIALIZE_BOUNDING_SPHERES = 0,
        MESH_RENDER_QUEUE_CALLBACK = 1
    };
    int    i, j;
    float  maxx, maxy, maxz, minx, miny, minz;
    float  vertex_position[4];
    float *current_mesh_sphere_components;
    float *verts;
    int    count;
    switch (moby->state) {
    case MESH_RENDER_INITIALIZE_BOUNDING_SPHERES: {
        for (i = 0; i <= 2; i++) {
            maxx = maxy = maxz = -1024.0f;
            minx = miny = minz = 1024.0f;
            {
                int k;
                for (k = 0; k < reflection_mesh_trio_b_vertex_counts[i]; k++) {
                    float x, y, z;
                    verts = ((float **)reflection_mesh_trio_b_position_tables)[i] + k * 3;
                    x = verts[0];
                    if (x > maxx)
                        maxx = x;
                    y = verts[1];
                    if (y > maxy)
                        maxy = y;
                    z = verts[2];
                    if (z > maxz)
                        maxz = z;
                    if (x < minx)
                        minx = x;
                    if (y < miny)
                        miny = y;
                    if (z < minz)
                        minz = z;
                }
            }
            {
                L16SingleSphere_2ea128 *mesh_bounding_sphere_table = D_L16_001E5390;
                L16SingleSphere_2ea128 *sphere = mesh_bounding_sphere_table + i;
                sphere->radius = 0.0f;
                sphere->x = (maxx + minx) * 0.5f;
                sphere->y = (maxy + miny) * 0.5f;
                sphere->z = (maxz + minz) * 0.5f;
            }
            for (j = 0; j < reflection_mesh_trio_b_vertex_counts[i]; j++) {
                float vertex_to_center_distance;
                current_mesh_sphere_components = (float *)(D_L16_001E5390 + i);
                vertex_position[0] =
                    ((float **)reflection_mesh_trio_b_position_tables)[i][j * 3 + 0];
                vertex_position[1] =
                    ((float **)reflection_mesh_trio_b_position_tables)[i][j * 3 + 1];
                vertex_position[2] =
                    ((float **)reflection_mesh_trio_b_position_tables)[i][j * 3 + 2];
                vertex_to_center_distance =
                    fast_vec_dist(vertex_position, current_mesh_sphere_components);
                if (vertex_to_center_distance > current_mesh_sphere_components[3])
                    current_mesh_sphere_components[3] = vertex_to_center_distance;
            }
        }
        moby->state = 1;
        moby->update_dist = moby->draw_dist = 255;
        break;
    }
    case MESH_RENDER_QUEUE_CALLBACK:
        add_draw_callback(env_map_a_draw, moby);
        break;
    }
}

