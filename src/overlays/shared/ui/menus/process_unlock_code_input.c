/* The buttons of an unlock code, as process_unlock_code_input numbers them. */
typedef unsigned char UnlockCodeButton;

enum {
    CODE_UP = 0,     /* PAD_UP */
    CODE_DOWN = 1,   /* PAD_DOWN */
    CODE_LEFT = 2,   /* PAD_LEFT */
    CODE_RIGHT = 3,  /* PAD_RIGHT */
    CODE_SQUARE = 4, /* PAD_SQUARE */
    CODE_CIRCLE = 5  /* PAD_CIRCLE */
};

extern UnlockCodeButton l00_unlock_code_comparison_table[256] __asm__("D_L00_001B9BA0");

void process_unlock_code_input(void) __asm__("FUN_L00_002831c0");

void process_unlock_code_input(void) {
    struct PadState *pad = &controller_state;
    int              staged_candidate_index_limit, candidate_index_limit;
    int              va, vb, vc;
    int              pressed, direction, recorded_input_count, j, code, index, matched;
    if ((*(long *)&pad->held_unmasked & 0xF) == 6) {
        pressed = *(s32 *)&pad->pressed_unmasked;
        if (!(pressed & 0xF0A0))
            return;

        if (*(int *)&unlock_code_input_count >= 20)
            return;
        if (pressed & 0x1000)
            direction = 0;
        else if (pressed & 0x4000)
            direction = 1;
        else if (pressed & 0x8000)
            direction = 2;
        else if (pressed & 0x2000)
            direction = 3;
        else
            direction = (pressed & 0x80) ? 4 : 5;
        recorded_input_count = *(int *)&unlock_code_input_count;
        unlock_code_input_sequence[recorded_input_count++] = direction;
        *(int *)&unlock_code_input_count = recorded_input_count;
        if (recorded_input_count != 20)
            return;
        code = -1;
        index = 2;
        /* Fakematch: the bound read back through memory stays a register compare */
        staged_candidate_index_limit = 0x93;
        candidate_index_limit = *(int *)&staged_candidate_index_limit;
        for (; index < candidate_index_limit; index++) {
            matched = 1;
            for (j = 0; j < 20; j++) {
                if (unlock_code_input_sequence[j] !=
                    l00_unlock_code_comparison_table[(j * index + index) & 0xff]) {
                    matched = 0;
                    break;
                }
            }
            if (matched) {
                code = index - 2;
                break;
            }
        }
        if (code == -1)
            return;
        va = code - 0x24;
        vb = code - 0x37;
        vc = code - 0x3d;
        if (code < 0x25) {
            D_0013D4C0[code] = 1;
            ((char *)items_acquired)[code] = 1;
        } else if ((unsigned)(code - 0x25) < 0x12) {
            unlock_planet(va);
        } else if ((unsigned)vb < 6) {
            char *code_flags = D_0013D388;
            code_flags[vb] = 1;
        } else if ((unsigned)vc < 0x1e) {
            unsigned char *selected_code_flag = item_unlocked + vc;
            if (!*selected_code_flag) {
                *selected_code_flag = 1;
                allocate_voice_for_bank_entry(1, 0, 0);
                queue_dialogue_message(0x53D6, -1);
            }
        }
    } else {
        *(int *)&unlock_code_input_count = 0;
    }
}

