void reveal_map_around_position(f32 *position) {
    s32               filters[16];
    f32               px;
    f32               py;
    s32               x;
    s32               y;
    s32               state;
    s32               level;
    s32               mode15;
    s32               mode16;
    s32               i;
    s32              *filter;
    s32               index;
    u32               flags;
    MapFilterCallback callback;
    s32               y_min;
    s32               column;
    s32               row_start;
    s32               row_end;
    s32               column_start;
    s32               column_end;
    s32               row;

    if (D_L00_00184218 == 0) {
        return;
    }
    if (rotated_map_transform_enabled != 0) {
        world_to_map_coords(position[0], position[1], &px, &py, current_level_index + 100);
    } else {
        world_to_map_coords(position[0], position[1], &px, &py, current_level_index);
    }
    x = (s32)(px * 512.0f) + 1;
    y = (s32)(py * 512.0f) + 1;
    if (x < 0 || y < 0 || x >= 512 || y >= 512) {
        return;
    }

    {
        /* Fakematch: a never-taken branch (cprop proves dead == 0, then jump deletes it).
           Retail had about 20 more insns before gcse that vanish later; they size the PRE
           hash table, which orders the frame slots of x - 16 and row + 1. */
        s32 dead = 0;
        if (x)
            dead = 0;
        if (dead) {
            ensure_menu_cache_entry(0);
            ensure_menu_cache_entry(0);
            ensure_menu_cache_entry(0);
            ensure_menu_cache_entry(0);
            ensure_menu_cache_entry(0);
            ensure_menu_cache_entry(0);
            ensure_menu_cache_entry(0);
        }
    }
    level = current_level_index;
    if (level < 0) {
        level = 0;
    }
    if (level >= 19) {
        level = 0;
    }
    state = 0;
    if (hero.state.control_mode == 17 || hero.state.control_mode == 18 ||
        hero.base_condition == 1) {
        state = 1;
    }
    mode16 = hero.state.control_mode == 16;
    mode15 = hero.state.control_mode == 15;
    y_min = y - 16;

    for (i = 0, filter = filters; i < 16; i++, filter++) {
        *filter = 1;
        if (i <= 0) {
            continue;
        }
        if (D_L00_00182BA0[level][i].lower != D_L00_00182BA0[level][i].upper) {
            f32 height = *(f32 *)((u8 *)hero.moby + 0x18);
            if (D_L00_00182BA0[level][i].lower > height ||
                height > D_L00_00182BA0[level][i].upper) {
                *filter = 0;
                continue;
            }
        }
        index = D_L00_00182BA0[level][i].index;
        flags = D_L00_00182BA0[level][i].flags;
        if (flags == 0) {
            continue;
        }
        if ((flags & 1) && !state) {
            *filter = 0;
            continue;
        }
        if ((flags & 2) && state) {
            *filter = 0;
            continue;
        }
        if ((flags & 4) && !mode16) {
            *filter = 0;
            continue;
        }
        if ((flags & 8) && mode16) {
            *filter = 0;
            continue;
        }
        if ((flags & 0x10) && !mode15) {
            *filter = 0;
            continue;
        }
        if ((flags & 0x20) && mode15) {
            *filter = 0;
            continue;
        }
        if ((flags & 0x40) && !hero.unk308) {
            *filter = 0;
            continue;
        }
        if ((flags & 0x80) && !D_L00_001844A8[index]) {
            *filter = 0;
            continue;
        }
        if (flags & 0x100) {
            callback = D_L00_00183F90[current_level_index][0];
            if (callback != 0 && !callback(position[0], position[1], position[2], x, y)) {
                *filter = 0;
                continue;
            }
        }
        if (flags & 0x200) {
            callback = D_L00_00183F90[current_level_index][1];
            if (callback != 0 && !callback(position[0], position[1], position[2], x, y)) {
                *filter = 0;
                continue;
            }
        }
        if (flags & 0x400) {
            callback = D_L00_00183F90[current_level_index][2];
            if (callback != 0 && !callback(position[0], position[1], position[2], x, y)) {
                *filter = 0;
                continue;
            }
        }
        if (flags & 0x800) {
            callback = D_L00_00183F90[current_level_index][3];
            if (callback != 0 && !callback(position[0], position[1], position[2], x, y)) {
                *filter = 0;
                continue;
            }
        }
        if (flags & 0x1000) {
            callback = D_L00_00183F90[current_level_index][4];
            if (callback != 0 && !callback(position[0], position[1], position[2], x, y)) {
                *filter = 0;
                continue;
            }
        }
        if (flags & 0x2000) {
            callback = D_L00_00183F90[current_level_index][5];
            if (callback != 0 && !callback(position[0], position[1], position[2], x, y)) {
                *filter = 0;
                continue;
            }
        }
        if (flags & 0x4000) {
            callback = D_L00_00183F90[current_level_index][6];
            if (callback != 0 && !callback(position[0], position[1], position[2], x, y)) {
                *filter = 0;
                continue;
            }
        }
        if (flags & 0x8000) {
            callback = D_L00_00183F90[current_level_index][7];
            if (callback != 0 && !callback(position[0], position[1], position[2], x, y)) {
                *filter = 0;
                continue;
            }
        }
    }

    row_start = y_min < 0 ? 0 : y_min;
    row_end = y + 16 > 511 ? 511 : y + 16;
    column_start = x - 16 < 0 ? 0 : x - 16;
    column_end = x + 16 > 511 ? 511 : x + 16;
    for (row = row_start; row < row_end; row++) {
        s32 exclusion_row = row - y + 16;
        s32 block_row = (row >> 5) * 16;
        s32 packed_row = row & 31;

        packed_row *= 16;

        for (column = column_start; column < column_end; column++) {
            u8 *pixel = D_L00_001841F0_lui.mask + row * 64 + column / 8;
            s32 bit;
            s32 test_column;
            s32 exclusion_offset;

            if (*pixel == 0) {
                continue;
            }
            bit = 1 << (column & 7);
            if (!(*pixel & bit)) {
                continue;
            }
            test_column = column - x + 16;
            exclusion_offset = exclusion_row * 4;
            if ((D_L00_001841F0_lui.exclusion[test_column / 8 + exclusion_offset] >>
                 (test_column % 8)) &
                1) {
                continue;
            }
            {
                u8 packed;
                u8 selected;
                ensure_menu_cache_entry((column >> 5) + block_row);
                packed = *(D_L00_001841F0_lui.packed + ((column & 31) >> 1) + packed_row);
                selected = (column & 1) ? packed >> 4 : packed & 15;
                if (filters[selected] != 0) {
                    *pixel &= ~bit;
                }
            }
        }
    }
}

