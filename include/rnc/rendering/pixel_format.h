#ifndef LOMBYTE_RNC_RENDERING_PIXEL_FORMAT_H
#define LOMBYTE_RNC_RENDERING_PIXEL_FORMAT_H

/* GS pixel storage format IDs shared by texture upload and image transfer. */

enum PixelStorageFormat {
    PIXEL_FORMAT_32_BIT = 0x0,
    PIXEL_FORMAT_24_BIT = 0x1,
    PIXEL_FORMAT_16_BIT = 0x2,
    PIXEL_FORMAT_16_BIT_ALTERNATE = 0xA,
    PIXEL_FORMAT_8_BIT = 0x13,
    PIXEL_FORMAT_4_BIT = 0x14,
    PIXEL_FORMAT_8_BIT_ALTERNATE = 0x1B,
    PIXEL_FORMAT_4_BIT_ALTERNATE = 0x24,
    PIXEL_FORMAT_4_BIT_ALTERNATE_2 = 0x2C,
    PIXEL_FORMAT_32_BIT_ALTERNATE = 0x30,
    PIXEL_FORMAT_24_BIT_ALTERNATE = 0x31,
    PIXEL_FORMAT_16_BIT_ALTERNATE_2 = 0x32,
    PIXEL_FORMAT_16_BIT_ALTERNATE_3 = 0x3A
};

#endif /* LOMBYTE_RNC_RENDERING_PIXEL_FORMAT_H */
